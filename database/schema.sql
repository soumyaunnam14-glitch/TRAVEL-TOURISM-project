-- Travel Tourism database schema for Supabase PostgreSQL.
-- Run this file in Supabase Dashboard -> SQL Editor -> New query.

create table if not exists public.destinations (
  id bigint generated by default as identity primary key,
  name text not null,
  country text not null,
  category text not null check (category in ('Beach', 'Mountains', 'Culture', 'Nature')),
  description text not null,
  duration_days integer not null default 3 check (duration_days between 1 and 60),
  starting_price_inr numeric(10,2) not null default 0 check (starting_price_inr >= 0),
  image_url text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.trip_requests (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  name text not null check (char_length(name) between 2 and 80),
  email text not null check (char_length(email) <= 254),
  destination_id bigint not null references public.destinations(id) on delete restrict,
  travel_date date not null,
  travellers integer not null check (travellers between 1 and 20),
  message text check (message is null or char_length(message) <= 1000),
  status text not null default 'new' check (status in ('new', 'contacted', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists idx_destinations_category_active
  on public.destinations(category, is_active);
create index if not exists idx_trip_requests_created_at
  on public.trip_requests(created_at desc);
create index if not exists idx_trip_requests_destination
  on public.trip_requests(destination_id);

-- Enable RLS. No public policies are created because the Express backend uses
-- the server-only service-role key after validating requests. Never expose that key.
alter table public.destinations enable row level security;
alter table public.trip_requests enable row level security;

